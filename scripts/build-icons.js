import fs from 'fs';
import path from 'path';
import { globSync } from 'glob';
import subsetFont from 'subset-font';

// Self-hosted Font Awesome with only the icons the site uses.
// The full CDN stylesheet has ~1,500 icons (~60 KB CSS + ~75 KB per font); we use ~70.
// Scans the source for "fa-<name>", writes a small CSS (bundled via main.jsx) and
// subsetted woff2 fonts. Runs before dev/build, so new icons are picked up automatically.

const FA_DIR = path.resolve('node_modules/@fortawesome/fontawesome-free');
const OUT_CSS = path.resolve('src/assets/icons.css');
const OUT_FONTS_DIR = path.resolve('public/fonts');

const FONTS = [
    { style: 'solid', file: 'fa-solid-900', family: 'Font Awesome 5 Free', weight: 900, classes: ['.fa', '.fas'] },
    { style: 'regular', file: 'fa-regular-400', family: 'Font Awesome 5 Free', weight: 400, classes: ['.far'] },
    { style: 'brands', file: 'fa-brands-400', family: 'Font Awesome 5 Brands', weight: 400, classes: ['.fab'] }
];

// Same base rules as fontawesome.css (sizes, spin, etc.), without the icon list
const BASE_CSS = `.fa,.fas,.far,.fab{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:inline-block;font-style:normal;font-variant:normal;text-rendering:auto;line-height:1}
.fa-lg{font-size:1.33333em;line-height:.75em;vertical-align:-.0667em}
.fa-xs{font-size:.75em}.fa-sm{font-size:.875em}.fa-1x{font-size:1em}.fa-2x{font-size:2em}.fa-3x{font-size:3em}.fa-4x{font-size:4em}.fa-5x{font-size:5em}
.fa-fw{text-align:center;width:1.25em}
.fa-spin{animation:fa-spin 2s infinite linear}.fa-pulse{animation:fa-spin 1s infinite steps(8)}
@keyframes fa-spin{0%{transform:rotate(0deg)}100%{transform:rotate(360deg)}}
`;

function usedIconNames() {
    const files = globSync(['src/**/*.{js,jsx}', 'index.html'], { ignore: ['src/assets/**'] });
    const names = new Set();
    for (const file of files) {
        const content = fs.readFileSync(file, 'utf8');
        for (const match of content.matchAll(/fa-([a-z0-9-]+)/g)) names.add(match[1]);
    }
    return names;
}

// name -> unicode, from the official stylesheet
function iconCodepoints() {
    const css = fs.readFileSync(path.join(FA_DIR, 'css/all.css'), 'utf8');
    const map = new Map();
    for (const match of css.matchAll(/\.fa-([a-z0-9-]+):before\s*{\s*content:\s*"\\([0-9a-f]+)"/g)) {
        map.set(match[1], match[2]);
    }
    return map;
}

async function buildIcons() {
    const codepoints = iconCodepoints();
    const used = usedIconNames();

    // Template literals like `fa-caret-${dir}` show up as the prefix "caret-": include every icon with it
    const icons = [...codepoints.keys()].filter(name =>
        used.has(name) || [...used].some(u => u.endsWith('-') && name.startsWith(u))
    ).sort();

    fs.mkdirSync(OUT_FONTS_DIR, { recursive: true });
    let css = `/* Generated by scripts/build-icons.js — do not edit. Font Awesome Free 5.15.4 (https://fontawesome.com/license/free) */\n${BASE_CSS}`;

    for (const font of FONTS) {
        const glyphs = icons.filter(name => fs.existsSync(path.join(FA_DIR, 'svgs', font.style, `${name}.svg`)));
        if (glyphs.length === 0) continue;

        const text = glyphs.map(name => String.fromCodePoint(parseInt(codepoints.get(name), 16))).join('');
        const source = fs.readFileSync(path.join(FA_DIR, 'webfonts', `${font.file}.woff2`));
        const subset = await subsetFont(source, text, { targetFormat: 'woff2' });
        fs.writeFileSync(path.join(OUT_FONTS_DIR, `${font.file}.woff2`), subset);

        css += `@font-face{font-family:'${font.family}';font-style:normal;font-weight:${font.weight};font-display:block;src:url("/fonts/${font.file}.woff2") format("woff2")}\n`;
        css += `${font.classes.join(',')}{font-family:'${font.family}';font-weight:${font.weight}}\n`;
        console.log(`🔤 ${font.file}: ${glyphs.length} icones (${(subset.length / 1024).toFixed(1)} KB)`);
    }

    for (const name of icons) {
        css += `.fa-${name}:before{content:"\\${codepoints.get(name)}"}\n`;
    }

    fs.writeFileSync(OUT_CSS, css, 'utf8');
    console.log(`✅ ${icons.length} icones -> src/assets/icons.css (${(css.length / 1024).toFixed(1)} KB)`);
}

buildIcons();
